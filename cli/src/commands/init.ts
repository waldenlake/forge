/**
 * Claude Code hook commands for context management seed injection.
 * PreCompact: injects handoff state before compaction so /resume can recover.
 * PostCompact: re-injects after compaction in case the seed was partially lost.
 */
const CLAUDE_HOOKS_TEMPLATE = {
  PreCompact: [
    {
      matcher: "",
      hooks: [
        {
          type: "command",
          command: ".forge/bin/forge handoff:get",
        },
      ],
    },
  ],
  PostCompact: [
    {
      matcher: "",
      hooks: [
        {
          type: "command",
          command: ".forge/bin/forge handoff:get",
        },
      ],
    },
  ],
};

function writeJson(payload: unknown): void {
  process.stdout.write(`${JSON.stringify(payload)}\n`);
}

function ensureDirectory(path: string, created: string[]): void {
  if (!existsSync(path)) {
    created.push(path);
  }

  mkdirSync(path, { recursive: true });
}

function existingConfigError(cwd: string): string | null {
  const targetPath = join(cwd, ".forge", "config.json");

  if (!existsSync(targetPath)) {
    return null;
  }

  try {
    const config = JSON.parse(readFileSync(targetPath, "utf8")) as {
      version?: unknown;
    };

    if (config.version === "1.0") {
      return "config.json already exists; run migrate";
    }
  } catch {
    return "config.json already exists; run status or migrate";
  }

  return "config.json already exists; run status or migrate";
}

